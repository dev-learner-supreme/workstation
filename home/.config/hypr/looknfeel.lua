  decoration = {
    rounding = 4,
    active_opacity = 1.0,
    inactive_opacity = 1.0,
  },
})

-- Force 100% solid opacity across all apps (disables system-wide translucency)
o.window(".*", { tag = "-default-opacity", opacity = "1.0 1.0" })

-- Breeze cursor (the KDE default); size stays at Omarchy's 24.
hl.env("XCURSOR_THEME", "breeze_cursors")
hl.env("HYPRCURSOR_THEME", "breeze_cursors")

